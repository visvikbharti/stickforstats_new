function getTestName(testType) {
  const names = {
    'two-sample-t': 'Two-Sample Independent t-test',
    'one-sample-t': 'One-Sample t-test',
    'paired-t': 'Paired t-test',
    'anova': 'One-Way ANOVA',
    'correlation': 'Correlation Test',
    'chi-square': 'Chi-Square Test',
    'mann-whitney': 'Mann-Whitney U Test',
    'wilcoxon': 'Wilcoxon Signed-Rank Test',
    'kruskal-wallis': 'Kruskal-Wallis Test'
  };
  return names[testType] || testType;
}

/**
 * Download code as a file
 *
 * @param {string} code - The code to download
 * @param {string} language - 'R' or 'Python'
 * @param {string} testType - Type of test for filename
 */
export function downloadCode(code, language, testType) {
  const extension = language === 'R' ? 'R' : 'py';
  const filename = `power_analysis_${testType}_${new Date().toISOString().split('T')[0]}.${extension}`;

  const blob = new Blob([code], { type: 'text/plain' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  a.click();
  URL.revokeObjectURL(url);
}

