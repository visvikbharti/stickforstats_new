function generatePythonCodeCorrelation(mode, alpha, power, r, n, alt, results) {
  const altPy = alt === 'two-sided' ? 'two-sided' : alt === 'greater' ? 'larger' : 'smaller';

  return `# Correlation Test: Power Analysis
# ============================================================================
# Using Fisher's z transformation for correlation power analysis
# ============================================================================
from scipy.stats import norm
import math

# Parameters
r = ${r}         # Expected correlation
n = ${n}         # Sample size
power_target = ${power}  # Desired power
alpha = ${alpha}  # Significance level
alternative = "${altPy}"

# Fisher's z transformation
def fisher_z(r):
    return 0.5 * math.log((1 + r) / (1 - r))

# Standard error of Fisher's z
def fisher_se(n):
    return 1 / math.sqrt(n - 3)

${mode === 'power' ? `
# Calculate power
z_r = fisher_z(r)
se = fisher_se(n)

if alternative == "two-sided":
    z_crit = norm.ppf(1 - alpha / 2)
    power_result = norm.cdf(z_r / se - z_crit) + norm.cdf(-z_r / se - z_crit)
else:
    z_crit = norm.ppf(1 - alpha)
    power_result = norm.cdf(z_r / se - z_crit)

print(f"Correlation Power Analysis")
print(f"=" * 40)
print(f"Expected Correlation: {r}")
print(f"Sample Size: {n}")
print(f"Fisher's z: {z_r:.4f}")
print(f"-" * 40)
print(f"Achieved Power: {power_result:.4f} ({power_result*100:.2f}%)")

# StickForStats Result: ${results.power ? (results.power * 100).toFixed(2) + '%' : 'N/A'}
` : mode === 'sampleSize' ? `
# Calculate sample size
z_r = fisher_z(r)
z_alpha = norm.ppf(1 - alpha / 2) if alternative == "two-sided" else norm.ppf(1 - alpha)
z_beta = norm.ppf(power_target)

n_required = math.ceil(((z_alpha + z_beta) / z_r) ** 2 + 3)

print(f"Correlation Sample Size Calculation")
print(f"=" * 40)
print(f"Expected Correlation: {r}")
print(f"Target Power: {power_target}")
print(f"-" * 40)
print(f"Required Sample Size: {n_required}")

# StickForStats Result: n = ${results.n || results.totalN || 'N/A'}
` : `
# Calculate minimum detectable correlation
# Binary search for effect size
def calc_power_for_r(r_test, n, alpha, alternative):
    z_r = fisher_z(r_test)
    se = fisher_se(n)
    if alternative == "two-sided":
        z_crit = norm.ppf(1 - alpha / 2)
        return norm.cdf(z_r / se - z_crit) + norm.cdf(-z_r / se - z_crit)
    else:
        z_crit = norm.ppf(1 - alpha)
        return norm.cdf(z_r / se - z_crit)

r_min, r_max = 0.01, 0.99
while r_max - r_min > 0.001:
    r_mid = (r_min + r_max) / 2
    power_at_mid = calc_power_for_r(r_mid, n, alpha, alternative)
    if power_at_mid < power_target:
        r_min = r_mid
    else:
        r_max = r_mid

min_r = (r_min + r_max) / 2

print(f"Correlation Effect Size Calculation")
print(f"=" * 40)
print(f"Sample Size: {n}")
print(f"Target Power: {power_target}")
print(f"-" * 40)
print(f"Minimum Detectable Correlation: {min_r:.4f}")

# StickForStats Result: r = ${results.effectSize ? results.effectSize.toFixed(4) : 'N/A'}
`}
`;
}

