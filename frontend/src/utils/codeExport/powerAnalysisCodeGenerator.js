/**
 * Pitman asymptotic relative efficiency of a rank test against its parametric counterpart, by the
 * distribution the DATA are assumed to come from.
 *
 * Both rank-test generators used to hardcode `const are = 0.955` and tell the reader "for normally
 * distributed data" -- while the tool above them lets the user choose the parent distribution and
 * computes with the matching ARE. So a user who selected Laplace was shown n = 43 per group and
 * handed a script that computes 68. The exported code contradicted the analysis it claimed to
 * reproduce, which is worse than no script at all: it is the artifact that outlives the session.
 *
 * 3/π is also the WRONG default to fall back on silently. It is the efficiency under NORMALITY --
 * an odd assumption for a test chosen precisely because normality failed -- and the "~5% larger
 * samples" line it justified points the wrong way for every heavier-tailed parent, where the rank
 * test needs FEWER subjects, not more.
 *
 * Mirrors ARE_VS_PARAMETRIC in backend/core/hp_power_analysis_comprehensive.py.
 */
const ARE_BY_PARENT = {
  normal: 3 / Math.PI, // ~0.955
  uniform: 1.0,
  logistic: Math.PI ** 2 / 9, // ~1.097
  laplace: 1.5,
  exponential: 3.0,
};

const PARENT_LABEL = {
  normal: 'normal',
  uniform: 'uniform',
  logistic: 'logistic',
  laplace: 'Laplace (heavy-tailed)',
  exponential: 'exponential (skewed)',
};

/**
 * The ARE the displayed answer was actually computed with.
 *
 * Prefer the value the BACKEND returned: that is the one the number on screen came from, so the
 * script and the screen cannot disagree about the arithmetic.
 *
 * But only when it AGREES with the parent the script is about to name. `results` and
 * `parentDistribution` come from different places -- the former is the last completed run, the
 * latter is live UI state -- so a caller that lets them drift would have this function print
 *
 *     # This analysis assumes a Laplace (heavy-tailed) parent, ARE = 0.9549
 *
 * naming one distribution and computing with another, in a single line. (PowerAnalysisTool no
 * longer lets them drift -- it clears `results` when any input changes -- but a generator that is
 * only correct because its caller is careful is one refactor away from lying again, and this file
 * writes the artifact that outlives the session.)
 *
 * On disagreement the STATED parent wins, because that is what the surrounding prose commits to.
 */
const areFor = (results, parentDistribution) => {
  const table = ARE_BY_PARENT[parentDistribution] ?? ARE_BY_PARENT.normal;
  const fromBackend = results && results.are;

  if (typeof fromBackend !== 'number' || !Number.isFinite(fromBackend)) return table;

  // Same parent -> use the backend's value (it is the exact one the displayed answer used).
  // Different parent -> `results` is stale; the script must describe the parent it names.
  return Math.abs(fromBackend - table) < 1e-3 ? fromBackend : table;
};

/**
 * Generate R code for power analysis
 *
 * @param {Object} params - Analysis parameters
 * @param {string} params.testType - Type of statistical test
 * @param {string} params.calculationMode - 'power', 'sampleSize', or 'effectSize'
 * @param {number} params.alpha - Significance level
 * @param {number} params.power - Statistical power (1-β)
 * @param {number} params.effectSize - Effect size value
 * @param {number} params.sampleSize - Sample size (n)
 * @param {number} params.sampleSize2 - Sample size for group 2 (if applicable)
 * @param {number} params.numGroups - Number of groups (for ANOVA)
 * @param {string} params.alternative - 'two-sided', 'greater', or 'less'
 * @param {Object} params.results - Calculation results
 * @returns {string} R code
 */
export function generateRCode(params) {
  const {
    testType,
    calculationMode,
    alpha = 0.05,
    power = 0.80,
    effectSize = 0.5,
    sampleSize = 30,
    sampleSize2 = 30,
    numGroups = 3,
    alternative = 'two-sided',
    parentDistribution = 'normal',
    results = {}
  } = params;

  const timestamp = new Date().toISOString();
  const altR = alternative === 'two-sided' ? 'two.sided' : alternative;

  let code = `# ============================================================================
# Power Analysis - Generated by StickForStats
# ============================================================================
# Generated: ${timestamp}
# Test Type: ${getTestName(testType)}
# Calculation Mode: ${calculationMode}
#
# Scientific Foundation:
# - Cohen, J. (1988). Statistical power analysis for the behavioral sciences.
# - Faul, F., et al. (2007). G*Power 3: A flexible statistical power analysis program.
# ============================================================================

# Install required packages (run once)
# install.packages("pwr")
# install.packages("WebPower")  # For additional tests

# Load libraries
library(pwr)

`;

  // Generate test-specific code
  switch (testType) {
    case 'two-sample-t':
      code += generateRCodeTwoSampleT(calculationMode, alpha, power, effectSize, sampleSize, sampleSize2, altR, results);
      break;
    case 'one-sample-t':
      code += generateRCodeOneSampleT(calculationMode, alpha, power, effectSize, sampleSize, altR, results);
      break;
    case 'paired-t':
      code += generateRCodePairedT(calculationMode, alpha, power, effectSize, sampleSize, altR, results);
      break;
    case 'anova':
      code += generateRCodeANOVA(calculationMode, alpha, power, effectSize, sampleSize, numGroups, results);
      break;
    case 'correlation':
      code += generateRCodeCorrelation(calculationMode, alpha, power, effectSize, sampleSize, altR, results);
      break;
    case 'chi-square':
      code += generateRCodeChiSquare(calculationMode, alpha, power, effectSize, sampleSize, params.degreesOfFreedom || 1, results);
      break;
    case 'mann-whitney':
    case 'wilcoxon':
    case 'kruskal-wallis':
      code += generateRCodeNonParametric(testType, calculationMode, alpha, power, effectSize, sampleSize, numGroups, altR, results, parentDistribution);
      break;
    default:
      code += `# Test type "${testType}" code generation not yet implemented\n`;
  }

  code += `
# ============================================================================
# Interpretation Guide
# ============================================================================
# Cohen's Effect Size Benchmarks:
#   - Cohen's d (t-tests): Small=0.2, Medium=0.5, Large=0.8
#   - Cohen's f (ANOVA):   Small=0.10, Medium=0.25, Large=0.40
#   - Correlation r:       Small=0.10, Medium=0.30, Large=0.50
#   - Cohen's w (Chi-sq):  Small=0.10, Medium=0.30, Large=0.50
#
# Power Interpretation:
#   - 80% power is the conventional minimum for most research
#   - 90% power is recommended for clinical trials
#   - 95% power is used when Type II errors are costly
#
# Note: Power analysis should be conducted BEFORE data collection (a priori).
# Post-hoc power analysis is generally uninformative.
# ============================================================================
`;

  return code;
}

