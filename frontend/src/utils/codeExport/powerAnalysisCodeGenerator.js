function generateRCodeTwoSampleT(mode, alpha, power, d, n1, n2, alt, results) {
  const ratio = n2 / n1;

  if (mode === 'power') {
    return `# Two-Sample Independent t-test: Calculate Power
# Parameters
d <- ${d}        # Cohen's d effect size
n1 <- ${n1}      # Sample size group 1
n2 <- ${n2}      # Sample size group 2
alpha <- ${alpha}  # Significance level
alternative <- "${alt}"

# Calculate power using pwr package
# Note: pwr.t2n.test handles unequal sample sizes
result <- pwr.t2n.test(
  n1 = n1,
  n2 = n2,
  d = d,
  sig.level = alpha,
  alternative = alternative
)

# Display results
print(result)
cat("\\n")
cat("Achieved Power:", round(result$power * 100, 2), "%\\n")
cat("Effect Size (Cohen's d):", d, "\\n")
cat("Total Sample Size:", n1 + n2, "\\n")

# StickForStats Result: ${results.power ? (results.power * 100).toFixed(2) + '%' : 'N/A'}
`;
  } else if (mode === 'sampleSize') {
    return `# Two-Sample Independent t-test: Calculate Sample Size
# Parameters
d <- ${d}        # Cohen's d effect size
power <- ${power}  # Desired power
alpha <- ${alpha}  # Significance level
alternative <- "${alt}"

# Calculate required sample size
result <- pwr.t.test(
  d = d,
  power = power,
  sig.level = alpha,
  type = "two.sample",
  alternative = alternative
)

# Display results
print(result)
cat("\\n")
cat("Required n per group:", ceiling(result$n), "\\n")
cat("Total sample size:", ceiling(result$n) * 2, "\\n")

# For unequal allocation (ratio = ${ratio}):
# n1 = ceiling(result$n)
# n2 = ceiling(result$n * ${ratio})

# StickForStats Result: n = ${results.totalN || results.n1 + results.n2 || 'N/A'}
`;
  } else {
    return `# Two-Sample Independent t-test: Calculate Minimum Detectable Effect Size
# Parameters
n1 <- ${n1}      # Sample size group 1
n2 <- ${n2}      # Sample size group 2
power <- ${power}  # Desired power
alpha <- ${alpha}  # Significance level
alternative <- "${alt}"

# Calculate minimum detectable effect size
# Using pwr.t2n.test with n specified, solving for d
result <- pwr.t2n.test(
  n1 = n1,
  n2 = n2,
  power = power,
  sig.level = alpha,
  alternative = alternative
)

# Display results
print(result)
cat("\\n")
cat("Minimum Detectable Effect Size (Cohen's d):", round(result$d, 4), "\\n")

# StickForStats Result: d = ${results.effectSize ? results.effectSize.toFixed(4) : 'N/A'}
`;
  }
}

