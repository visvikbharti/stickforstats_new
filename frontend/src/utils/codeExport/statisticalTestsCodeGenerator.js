function formatDataForR(data) {
  if (!Array.isArray(data)) return String(data);
  return data.map(v => {
    if (typeof v === 'number') {
      return Number.isInteger(v) ? v : v.toFixed(6);
    }
    return v;
  }).join(', ');
}

